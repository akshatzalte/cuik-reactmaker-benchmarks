#!/usr/bin/env python
"""
One-time script to generate golden reference files for test_reaction_features.py.

Run once in the cuikmm env from the repo root:
    conda activate cuikmm
    python tests/python/gen_reaction_refs.py

Writes tests/data/sample_rxns_100_<VERSION>_<MODE>_ref.xz for all
4 atom featurizer versions × 6 reaction modes = 24 files.

The goldens are generated by the C++ batch_reaction_featurizer itself (not
from Chemprop's Python CGR). Correctness of the C++ output vs. Chemprop's
CondensedGraphOfReactionFeaturizer was verified separately (max_diff=0 on
E2/SN2 data across all 6 modes before these goldens were generated).

Do NOT commit this script.
"""

import lzma
import os
import pickle

import numpy as np
import pandas as pd

import cuik_molmaker

# cuik-molmaker repo test-data dir (this script lives in the benchmarks repo,
# so the path is absolute rather than relative to __file__).
CUIK_DATA_DIR = os.environ.get(
    "CUIK_DATA_DIR", "/data3/akshatz/cuik-molmaker/tests/data")
DATA_DIR = CUIK_DATA_DIR
INPUT_CSV = os.path.join(DATA_DIR, "sample_rxns_100.csv")

REACTION_MODES = [
    "REAC_DIFF",
    "REAC_PROD",
    "PROD_DIFF",
    "REAC_DIFF_BALANCE",
    "REAC_PROD_BALANCE",
    "PROD_DIFF_BALANCE",
]

# V1/V2/ORGANIC share the same bond features; RIGR uses a reduced set.
FEATURIZER_CONFIGS = {
    "V1": {
        "atom_onehot": ["atomic-number", "total-degree", "formal-charge",
                        "chirality", "num-hydrogens", "hybridization"],
        "atom_float": ["aromatic", "mass"],
        "bond": ["is-null", "bond-type-onehot", "conjugated", "in-ring", "stereo"],
    },
    "V2": {
        "atom_onehot": ["atomic-number-common", "total-degree", "formal-charge",
                        "chirality", "num-hydrogens", "hybridization-expanded"],
        "atom_float": ["aromatic", "mass"],
        "bond": ["is-null", "bond-type-onehot", "conjugated", "in-ring", "stereo"],
    },
    "ORGANIC": {
        "atom_onehot": ["atomic-number-organic", "total-degree", "formal-charge",
                        "chirality", "num-hydrogens", "hybridization-organic"],
        "atom_float": ["aromatic", "mass"],
        "bond": ["is-null", "bond-type-onehot", "conjugated", "in-ring", "stereo"],
    },
    "RIGR": {
        "atom_onehot": ["atomic-number-common", "total-degree", "num-hydrogens"],
        "atom_float": ["mass"],
        # RIGR uses reduced bond features — only 2 vs 14 for V1/V2/ORGANIC
        "bond": ["is-null", "in-ring"],
    },
}


def main():
    df = pd.read_csv(INPUT_CSV)
    # rxn_smiles column format: "reactant>>product"
    reac_smiles = [s.split(">>")[0] for s in df["rxn_smiles"]]
    prod_smiles = [s.split(">>")[1] for s in df["rxn_smiles"]]

    for version, cfg in FEATURIZER_CONFIGS.items():
        atom_onehot = cuik_molmaker.atom_onehot_feature_names_to_array(cfg["atom_onehot"])
        atom_float = cuik_molmaker.atom_float_feature_names_to_array(cfg["atom_float"])
        bond_feats = cuik_molmaker.bond_feature_names_to_array(cfg["bond"])

        for mode in REACTION_MODES:
            mode_int = cuik_molmaker.reaction_mode_to_int(mode)
            V, E, edge_index, rev_edge_index, batch = cuik_molmaker.batch_reaction_featurizer(
                reac_smiles, prod_smiles,
                atom_onehot, atom_float, bond_feats,
                True, False, False, mode_int,
            )
            ref = {
                "reac_smiles": reac_smiles,
                "prod_smiles": prod_smiles,
                "V": V,
                "E": E,
                "edge_index": edge_index,
                "rev_edge_index": rev_edge_index,
                "batch": batch,
            }
            out_path = os.path.join(DATA_DIR, f"sample_rxns_100_{version}_{mode}_ref.xz")
            with lzma.open(out_path, "wb") as f:
                pickle.dump(ref, f)
            print(f"Wrote {out_path}  V={V.shape}  E={E.shape}")


if __name__ == "__main__":
    main()
